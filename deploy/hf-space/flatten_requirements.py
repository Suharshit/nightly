"""Write one self-contained requirements.txt for the Space.

The Space copies requirements.txt alone to /tmp before installing it, so `-r other.txt` lines
cannot be followed there. This expands them, drops pip options (the PyTorch CPU index) and the
CPU torch pin, and keeps the first pin seen for each package (the Space file's own pins win).

Usage: python flatten_requirements.py deploy/hf-space/requirements.txt OUT
"""

import re
import sys
from pathlib import Path


def expand(path: Path, seen: set[Path]) -> list[str]:
    path = path.resolve()
    if path in seen:
        return []
    seen.add(path)
    lines = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if line.startswith(("-r ", "--requirement ")):
            lines += expand(path.parent / line.split(maxsplit=1)[1], seen)
        elif line.startswith("-"):
            continue                      # --extra-index-url and other pip options
        else:
            lines.append(line)
    return lines


def name(req: str) -> str:
    return re.split(r"[\s<>=!~\[;]", req, maxsplit=1)[0].lower().replace("_", "-")


def main() -> None:
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    kept: dict[str, str] = {}
    for req in expand(src, set()):
        if "+cpu" in req:
            continue
        kept.setdefault(name(req), req)
    out.write_text("# Generated by deploy/hf-space/flatten_requirements.py; edit the sources.\n"
                   + "\n".join(kept.values()) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
